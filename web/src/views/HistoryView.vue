    <div class="callout">
      <b>两套纪年并行，这本身就是一条世界观信息。</b>
    </div>
    <table>
      <tr><th>纪年</th><th>谁用</th><th>怎么算</th><th>例</th></tr>
      <tr><td><b>潮数纪年</b></td><td><b>民间 · 冒险者 · 各族部落</b></td><td><b>一次潮涨 ＝ 一个「潮」</b>，往前倒数</td><td>「那是上一个潮的事了」</td></tr>
      <tr><td><b>誓约纪元</b></td><td><b>城邦官府 · 教会 · 公会文书</b></td><td>以三千年前那纸停战书为元年</td><td>誓约纪元 30000 年 · 静潮三月</td></tr>
      <tr><td><b>建炉纪年</b></td><td><b>矮人九炉 / 北邦</b></td><td>以九炉议会立约之年为元年</td><td>建炉 1412 年</td></tr>
    </table>
    <div class="annotate">
      <span class="lbl">为什么百姓记潮不记年（这条最重要）</span>
      <b>对一个凡人来说，「年」什么也不说明，「潮」会决定他今年能不能收到粮食。</b><br>
      十四次潮涨改写了大陆格局十四次——<b>这才是他们的时间刻度。</b>
    </div>
    <ul>
      <li>一年 <b>12 个月、360 天</b>；余 <b>5 天</b>为「<b>无月日</b>」，各族各过各的，<b>不计入任何纪年</b>。</li>
      <li><b>每月按潮势命名</b>：<b>潮起 / 潮盛 / 潮落 / 静潮</b> 四组，每组三月——<b>连月份名都在提醒你这个世界怕什么。</b></li>
      <li>各族有自己的月名；<b>公会文书统一用「誓约纪元 ＋ 月份序号」</b>——这是公会「中立」的技术基础。</li>
      <li><b>第 15 次潮涨没有对应的月名</b>——它一旦到来，历法本身要改。
        <span class="dim"><b>可用的细节钩子：民间已经开始提前给那个月造新词，而教会禁止任何人写。</b></span></li>
    </ul>
