        <p class="dim"><b>结果</b>：<b>内海 = 相对安全</b>（有大阵、有航线、有海裔）；<b>外海 = 真正的危险区</b>。人类与海裔因此都聚在内海一带——<b>于是内海沿岸成了五族杂处的走廊</b>，尽头就是公会自治领。</p>
      </div>
      <div class="card">
        <h3>咽喉：内海出海口</h3>
        <p>若内海敞开，黑暗方的舰队可以从东南直插人类腹地，整条西南防线将毫无意义。</p>
        <p class="dim">所以设定上，内海的<b>唯一深水出海口</b>被上古战场延伸出的<b>残岛链</b>扼住——所有大型船只必须逐一穿过狭窄水道，而每一段水道都在岸防与残岛炮台（矮人以太赋形阵）的射程内。</p>
      </div>
      <div class="card">
        <h3>禁区：半岛符文禁区</h3>
        <p>堕落半岛外围以太浓度致死，凡人无法长期停留。<b>唯一可通行路径由公会发证。</b></p>
        <p class="dim">这一条同时解决三件事：① 解释了为什么三万年来没有国家去抢半岛封存的太古宝库；② 解释了为什么只有零散冒险者能进出；③ 把「发证权」变成公会最硬的权力。</p>
      </div>
      <div class="card">
        <h3>命门：五位在位之神，一个都不能下场</h3>
        <p>龙岛雪峰 / 东境风眼 / 精灵圣林 / 深海宫殿 / 灰铁地心——<b>当代五位在位半神就住在这些地方。</b></p>
        <p class="dim"><b>而上古共约禁止半神直接干预凡俗。</b>所以神就坐在那里，<b>却不能下场打仗</b>——世界要靠凡人自己撑。守它们的分别是龙族（互不统属）、<b>没人（风眼只有天气）</b>、精灵（闭林）、海裔（不外传）、矮人（绝对中立）。</p>
        <p class="dim">铁律第 3 条又写着：<b>若位面壁垒崩溃，所有半神必须全员苏醒救世。</b>于是全世界最尖锐的问题变成——<b>谁来判定「崩溃」？谁在拖延这个判定？</b></p>
      </div>
      <div class="card">
        <h3>屏障：上古战场</h3>
        <p>从西南的焦土主岛到东南的残岛链，构成一道横亘在黑暗与主陆之间的破碎屏障。</p>
        <p class="dim">它挡不住半神，但挡得住军队、船队与兽潮——而近三万年里，需要被挡住的恰恰是后者。</p>
