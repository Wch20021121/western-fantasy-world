    <h2>教会教义与异端定义<span class="mark add">v10 补</span></h2>
    <p><b>教义三基</b>——只有三条，其余全是这三条的推论：</p>
    <div class="region-note">
      <div><b>① 光明印在圣山，且它终将自己选择。</b> → 教会的正统身份是<b>守候者</b>，不是<b>拥有者</b>。</div>
      <div><b>② 净「质」不治「形」。</b> 圣光只让扭曲的以太回归自然，<b>肉要靠精灵</b> → 教会必须承认<b>自己有一半是残缺的</b>，这是一切教内张力的源头。</div>
      <div><b>③ 蚀主已死，但黑暗印还活着。</b> → <b>战争没结束</b>，只是从「打他」变成了「守住封印」。</div>
    </div>
    <table>
      <tr><th>级</th><th>名称</th><th>定义</th><th>处置</th></tr>
      <tr><td><b>Ⅰ</b></td><td><b>偏差</b></td><td>对教义的解释与正统不同</td><td>辩论 · 训诫</td></tr>
      <tr><td><b>Ⅱ</b></td><td><b>僭越</b></td><td><b>未经遴选而自称承接圣光</b></td><td>剥夺教职</td></tr>
      <tr><td><b>Ⅲ</b></td><td><b>涉暗</b></td><td>接触黑暗系 · 佩戴仿印 · 买卖半岛之物</td><td><b>交公会发落</b>——教会自己不动手（这正是「半岛发证权」的另一面）</td></tr>
      <tr><td><b>Ⅳ</b></td><td><b>蚀染</b></td><td>体内确有黑暗以太</td><td><b>不判，直接净化</b>；净化失败者 → <b>公会的净化任务</b></td></tr>
