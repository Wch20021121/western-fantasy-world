      <b>能，但代价不对等，而且制度上几乎做不到。</b><br>
      ① <b>圣光</b>只能把扭曲的以太<b>推回自然态</b>，<b>推不回已经变形的肉</b> → 人回来了，形不一定回来；<br>
      ② <b>精灵的修形</b>能把肉修回去，<b>但清除不了黑暗以太</b> → 两者必须<b>同时、同地、由两族共同执行</b>；<br>
      ③ 而<b>精灵闭林、教会不认精灵的法</b> → <b>于是「救一个人」在制度上几乎不可能。</b>
